/* ============================================================================
   СКРИПТ СТРАНИЦЫ
   ----------------------------------------------------------------------------
   Здесь немного простого кода. Каждая часть подписана.
   Файл подключается в самом конце index.html, поэтому к моменту запуска
   вся страница уже загружена и элементы доступны.
   ========================================================================== */

(function () {
    "use strict";

    /* ------------------------------------------------------------------------
       1. ПЛАВНАЯ ПРОКРУТКА ПО ОГЛАВЛЕНИЮ
       Когда читатель кликает по пункту оглавления (ссылка вида href="#s3"),
       страница плавно прокручивается к нужному разделу, а не «прыгает».
       Заодно адрес в строке браузера обновляется на #s3 — ссылкой
       можно поделиться, и она откроется сразу на нужном разделе.
    ------------------------------------------------------------------------ */
    var anchors = document.querySelectorAll('a[href^="#"]');

    anchors.forEach(function (link) {
        link.addEventListener("click", function (event) {
            var targetId = link.getAttribute("href");

            // Пропускаем пустые и технические ссылки (например, href="#").
            if (!targetId || targetId === "#") {
                return;
            }

            var target = document.querySelector(targetId);
            if (!target) {
                return; // раздела с таким id нет — ведём себя как обычная ссылка
            }

            event.preventDefault(); // отменяем стандартный резкий переход

            target.scrollIntoView({
                behavior: "smooth", // плавно
                block: "start"      // верх раздела совмещаем с верхом экрана
            });

            // Обновляем адрес страницы без перезагрузки.
            if (history.pushState) {
                history.pushState(null, "", targetId);
            }
        });
    });

    /* ------------------------------------------------------------------------
       2. ПОДСТРАХОВКА ДЛЯ КАРТИНОК
       Основная логика «нет файла — показываем заглушку» уже встроена
       в сам тег <img> через атрибут onerror прямо в HTML. Этот блок —
       подстраховка: если картинку всё-таки добавили и она успешно
       загрузилась, заглушка под ней принудительно скрывается.
       Так не останется двойного изображения ни при каком раскладе.
    ------------------------------------------------------------------------ */
    var images = document.querySelectorAll(".figure__img");

    images.forEach(function (img) {
        // Если картинка уже загрузилась к моменту запуска скрипта.
        if (img.complete && img.naturalWidth > 0) {
            hidePlaceholder(img);
        }
        // Либо когда она догрузится позже.
        img.addEventListener("load", function () {
            hidePlaceholder(img);
        });
    });

    // Прячет серую заглушку, которая лежит сразу после картинки.
    function hidePlaceholder(img) {
        var placeholder = img.nextElementSibling;
        if (placeholder && placeholder.classList.contains("figure__placeholder")) {
            placeholder.style.display = "none";
        }
    }

})();
